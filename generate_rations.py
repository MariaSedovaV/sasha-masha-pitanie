def meal_photo(meal_type: str, dish: str) -> str:
    text = f"{meal_type} {dish}".lower()
    if str(meal_type).startswith("Перекус"):
        if "яйц" in text:
            return "images/photo-snack-egg.jpg"
        if "тофу" in text:
            return "images/photo-tofu.jpg"
